#!/usr/bin/env python3
"""Generate the local HTML reference lookup. No network access or build-time download."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'ThirdPartyNotices/WHATWGHTML/entities.json'
TARGET = ROOT / 'MyApp/EncodingCore/HTMLEntityTable.generated.swift'
EXPECTED_SHA = 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6'


def generate():
    raw = SOURCE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == EXPECTED_SHA, 'Unexpected upstream data; review snapshot and update provenance deliberately.'
    entries = json.loads(raw)
    assert len(entries) == 2231
    lines = []
    for name, value in sorted(entries.items()):
        assert name.startswith('&') and all(ord(c) < 128 for c in name)
        assert list(map(ord, value['characters'])) == value['codepoints']
        lines.append(name[1:] + '|' + ','.join(f'{point:X}' for point in value['codepoints']))
    packed = '\n'.join(lines)
    return '''// Generated by scripts/GenerateHTMLEntityTable.py; do not edit manually.
// WHATWG HTML named character references, retrieved 2026-10-19.
// https://html.spec.whatwg.org/entities.json
// SHA-256: ''' + EXPECTED_SHA + '''
// Copyright WHATWG (Apple, Google, Mozilla, Microsoft).
// BSD-3-Clause for incorporation into source code; see ThirdPartyNotices/WHATWGHTML/LICENSE.
import Foundation

enum HTMLEntityTable {
    static let maximumNameLength = ''' + str(max(len(name) - 1 for name in entries)) + '''
    static let entries: [String: String] = {
        var result = [String: String](minimumCapacity: 2231)
        for line in packed.split(separator: "\\n") {
            let fields = line.split(separator: "|")
            let scalars = fields[1].split(separator: ",").map { Unicode.Scalar(UInt32($0, radix: 16)!)! }
            result[String(fields[0])] = String(String.UnicodeScalarView(scalars))
        }
        return result
    }()
    static let names: [UInt32: String] = {
        var result: [UInt32: String] = [:]
        for (name, value) in entries where name.hasSuffix(";") && value.unicodeScalars.count == 1 {
            let scalar = value.unicodeScalars.first!.value
            if let previous = result[scalar], previous.count < name.count || (previous.count == name.count && previous < name) { continue }
            result[scalar] = name
        }
        for (scalar, name) in [(38, "amp;"), (60, "lt;"), (62, "gt;"), (34, "quot;"), (39, "apos;")] {
            result[UInt32(scalar)] = name
        }
        return result
    }()
    private static let packed = """
''' + packed + '''
"""
}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        assert TARGET.read_text() == content, 'Generated table is not current'
        print('HTML reference table is reproducible: 2231 entries, pinned SHA-256 verified.')
    else:
        TARGET.write_text(content)
        print('Generated', TARGET.relative_to(ROOT))
